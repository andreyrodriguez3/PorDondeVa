function reverseGeometry(geometry: LineString): LineString {
  return { type: 'LineString', coordinates: [...geometry.coordinates].reverse() };
}

/**
 * Creates (or updates) a route. By default it's bidirectional: an OUTBOUND variant
 * with the given geometry/stops, and an INBOUND variant that's simply the reverse of
 * both — same shape as the original San José-Palmares seed route, factored out
 * because `main()` now seeds several of these instead of one. Pass
 * `directions: 'outbound-only'` for a route with no real return trip (the field-test
 * company's placeholder), so a driver isn't shown two identically-named variants.
 */
async function seedRoute(
  companyId: string,
  args: {
    publicSlug: string;
    name: string;
    originLabel: string;
    destinationLabel: string;
    outboundHeadsign: string;
    inboundHeadsign: string;
    geometry: LineString;
    stops: LatLng[];
    scheduleHours: number[];
    directions?: 'both' | 'outbound-only';
  },
) {
  const route = await prisma.route.upsert({
    where: { companyId_publicSlug: { companyId, publicSlug: args.publicSlug } },
    update: {},
    create: {
      companyId,
      name: args.name,
      originLabel: args.originLabel,
      destinationLabel: args.destinationLabel,
      publicSlug: args.publicSlug,
      status: 'ACTIVE',
    },
  });

  const inboundGeometry = reverseGeometry(args.geometry);

  async function upsertVariant(direction: 'OUTBOUND' | 'INBOUND') {
    const geometry = direction === 'OUTBOUND' ? args.geometry : inboundGeometry;
    const headsign = direction === 'OUTBOUND' ? args.outboundHeadsign : args.inboundHeadsign;
    const existing = await prisma.routeVariant.findFirst({
      where: { routeId: route.id, direction },
    });
    return existing
      ? prisma.routeVariant.update({ where: { id: existing.id }, data: { geometry } })
      : prisma.routeVariant.create({
          data: {
            companyId,
            routeId: route.id,
            name: `${args.name} (${headsign})`,
            direction,
            headsign,
            geometry,
            isDefault: direction === 'OUTBOUND',
            status: 'ACTIVE',
          },
        });
  }

  const outbound = await upsertVariant('OUTBOUND');
  const inbound = args.directions === 'outbound-only' ? null : await upsertVariant('INBOUND');

  const stops = [];
  for (const stopData of args.stops) {
    const stop =
      (await prisma.stop.findFirst({ where: { companyId, name: stopData.name } })) ??
      (await prisma.stop.create({ data: { companyId, ...stopData } }));
    stops.push(stop);
  }

  const variantStopOrders = inbound
    ? ([
        [outbound, stops],
        [inbound, [...stops].reverse()],
      ] as const)
    : ([[outbound, stops]] as const);

  for (const [variant, order] of variantStopOrders) {
    for (const [sequence, stop] of order.entries()) {
      await prisma.routeVariantStop.upsert({
        where: { routeVariantId_stopId: { routeVariantId: variant.id, stopId: stop.id } },
        update: { sequence: sequence + 1 },
        create: {
          companyId,
          routeVariantId: variant.id,
          stopId: stop.id,
          sequence: sequence + 1,
        },
      });
    }
  }

  const baseDate = new Date('1970-01-01T06:00:00Z');
  for (const hour of args.scheduleHours) {
    const departureTime = new Date(baseDate);
    departureTime.setUTCHours(hour, 0, 0, 0);
    const existing = await prisma.schedule.findFirst({
      where: { routeVariantId: outbound.id, departureTime },
    });
    if (!existing) {
      await prisma.schedule.create({
        data: {
          companyId,
          routeVariantId: outbound.id,
          departureTime,
          daysOfWeek: [1, 2, 3, 4, 5],
          active: true,
        },
      });
    }
  }
}

